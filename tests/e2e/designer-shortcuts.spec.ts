import { expect, test } from '@playwright/test';

test('designer shortcuts duplicate subtrees, undo, redo, group, nudge and respect inputs and dialogs', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Edit Spirit cards', exact: true }).click();
  const layers = page.locator('.layer-row');
  const initial = await layers.count();
  await page.getByRole('button', { name: 'Add shape', exact: true }).click();
  await expect(layers).toHaveCount(initial + 1);
  await layers.last().click();
  await page.keyboard.press('Control+c');
  await page.keyboard.press('Control+v');
  await expect(layers).toHaveCount(initial + 2);
  await page.keyboard.press('Control+d');
  await expect(layers).toHaveCount(initial + 3);
  await page.keyboard.press('Control+z');
  await expect(layers).toHaveCount(initial + 2);
  await page.keyboard.press('Control+Shift+z');
  await expect(layers).toHaveCount(initial + 3);
  await layers.last().click();
  const x = page.getByLabel('X', { exact: true });
  const previous = Number(await x.inputValue());
  await page.keyboard.press('Shift+ArrowRight');
  await expect(x).toHaveValue(String(previous + 10));
  await x.focus();
  await page.keyboard.press('Control+a');
  await page.keyboard.press('Backspace');
  await expect(layers).toHaveCount(initial + 3);
  await x.blur();
  await layers.last().click();
  await page.keyboard.press('Control+g');
  await expect(layers).toHaveCount(initial + 4);
  await page.keyboard.press('Control+Shift+g');
  await expect(layers).toHaveCount(initial + 3);
  await page.keyboard.press('Control+x');
  await expect(layers).toHaveCount(initial + 2);
  await page.keyboard.press('Control+v');
  await expect(layers).toHaveCount(initial + 3);
  await page.keyboard.press('Control+a');
  await expect(page.locator('.layer-row.active')).not.toHaveCount(0);
  await page.keyboard.press('Escape');
  await expect(page.locator('.layer-row.active')).toHaveCount(0);
  await layers.last().click();
  await page.getByRole('button', { name: /Data bindings/ }).click();
  await page.keyboard.press('Delete');
  await expect(layers).toHaveCount(initial + 3);
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.keyboard.press('Delete');
  await expect(layers).toHaveCount(initial + 2);
});

test('designer wheel zoom anchors at pointer and pan does not drag layers', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Edit Spirit cards', exact: true }).click();
  await page.waitForTimeout(350); // Wait for the artboard entrance animation to finish before measuring.
  const board = page.locator('.artboard');
  const before = (await board.boundingBox())!;
  const sx = before.x + before.width * .3, sy = before.y + before.height * .3;
  await page.mouse.move(sx, sy);
  await page.mouse.wheel(0, -180);
  await expect.poll(async () => (await board.boundingBox())!.width).toBeGreaterThan(before.width);
  const zoomed = (await board.boundingBox())!;
  expect((sx - zoomed.x) / zoomed.width).toBeCloseTo(.3, 2);
  expect((sy - zoomed.y) / zoomed.height).toBeCloseTo(.3, 2);
  await page.mouse.move(sx, sy);
  await page.mouse.down({ button: 'middle' });
  await page.mouse.move(sx + 60, sy + 35, { steps: 4 });
  await page.mouse.up({ button: 'middle' });
  const panned = (await board.boundingBox())!;
  expect(panned.x - zoomed.x).toBeCloseTo(60, 0);
  expect(panned.y - zoomed.y).toBeCloseTo(35, 0);
  await page.locator('.layer-row').first().focus();
  await page.keyboard.down('Space');
  await page.mouse.move(sx, sy);
  await page.mouse.down();
  await page.mouse.move(sx + 25, sy + 20, { steps: 4 });
  await page.mouse.up();
  await page.keyboard.up('Space');
  const spacePan = (await board.boundingBox())!;
  expect(spacePan.x - panned.x).toBeCloseTo(25, 0);
  expect(spacePan.y - panned.y).toBeCloseTo(20, 0);
});
