test('multi-selection transforms, moves, clones, draws and deletes all selected pieces', async ({ page }) => {
  await page.goto('/');
  const p = (await workspace(page)).projects[0];
  const cards = p.instances.filter(i => i.componentId === p.components[0].id && !i.stack).slice(0, 2);
  const first = page.locator(`[data-piece-id="${cards[0].id}"]`), second = page.locator(`[data-piece-id="${cards[1].id}"]`);
  await first.click(); await second.click({ modifiers: ['Shift'] });
  await expect(page.locator('.table-piece.selected')).toHaveCount(2);
  await second.click({ modifiers: ['Control'] });
  await expect(page.locator('.table-piece.selected')).toHaveCount(1);
  await second.click({ modifiers: ['Shift'] });
  await first.hover(); await page.keyboard.press('e'); await page.keyboard.press('f');
  for (const card of cards) {
    await expect.poll(async () => (await workspace(page)).projects[0].instances.find(i => i.id === card.id)).toMatchObject({ rotation: card.rotation + 90, flipped: !card.flipped });
  }
  await page.getByLabel('Scale', { exact: true }).fill('0.5'); await page.getByLabel('Scale', { exact: true }).blur();
  for (const card of cards) await expect.poll(async () => (await workspace(page)).projects[0].instances.find(i => i.id === card.id)?.scale).toBe(.5);
  const from = (await first.boundingBox())!;
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2); await page.mouse.down();
  await page.keyboard.down('Alt'); await page.mouse.move(from.x + from.width / 2 + 60, from.y + from.height / 2 - 70, { steps: 8 });
  await page.mouse.up(); await page.keyboard.up('Alt');
  const afterMove = (await workspace(page)).projects[0].instances;
  const moved = cards.map(card => afterMove.find(i => i.id === card.id)!);
  expect(moved[0].x - cards[0].x).toBeCloseTo(moved[1].x - cards[1].x);
  expect(moved[0].x).not.toBe(cards[0].x);
  await first.hover(); await page.keyboard.press('Control+d');
  await expect(page.locator('.table-piece.selected')).toHaveCount(2);
  await expect.poll(async () => (await workspace(page)).projects[0].instances.length).toBe(p.instances.length + 2);
  await page.getByRole('button', { name: /^Draw to hand/ }).click();
  await expect(page.locator('.hand-card')).toHaveCount(2);
  await page.mouse.move(10, 70); await page.keyboard.press('Delete');
  await expect(page.locator('.hand-card')).toHaveCount(0);
  await expect.poll(async () => (await workspace(page)).projects[0].instances.length).toBe(p.instances.length);
  // A small box around a tabletop card selects through the current camera.
  const box = (await first.boundingBox())!;
  const viewport = (await page.locator('.table-viewport').boundingBox())!;
  await page.mouse.move(viewport.x + 100, viewport.y + 70); await page.mouse.down();
  await page.mouse.move(box.x + box.width + 8, box.y + box.height + 8, { steps: 8 });
  await expect(page.locator('.selection-marquee')).toBeVisible();
  await page.mouse.up();
  await expect(first).toHaveClass(/selected/);
});
